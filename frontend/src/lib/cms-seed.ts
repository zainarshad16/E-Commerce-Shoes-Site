const DEFAULT_SIZES = ['US 7', 'US 8', 'US 9', 'US 10', 'US 11', 'US 12', 'US 13'];

function makeSizes(prefix: string, counts: number[]) {
  return DEFAULT_SIZES.map((sizeLabel, index) => ({
    id: `${prefix.toLowerCase()}-sz-${index}`,
    sizeLabel,
    sku: `${prefix}-${sizeLabel.replace(/\s+/g, '')}`,
    stockCount: counts[index] ?? 6,
  }));
}

